const { chromium } = require('../.video-tools/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const output = path.resolve('deliverables/deployment');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  const results = [];
  page.on('pageerror', err => errors.push(err.message));
  const stamp = async (label) => page.evaluate(label => {
    const stamp = document.createElement('div');
    stamp.style.cssText = 'position:fixed;top:0;left:0;right:0;z-index:999999;background:#123747;color:white;padding:6px;font:13px Arial;text-align:center;pointer-events:none';
    stamp.textContent = label + ' | Captured ' + new Date().toLocaleString('en-US', { timeZone: 'America/New_York' }) + ' America/New_York | ' + location.href;
    document.body.append(stamp);
  }, label);
  const assert = (value, label) => { if (!value) throw new Error(label); results.push(label); };
  const base = process.env.VERIFY_URL || 'http://localhost:3000';
  const health = await page.request.get(base + '/api/health');
  assert(health.ok() && (await health.json()).data.status === 'ok', 'Packaged API health endpoint');
  await page.goto(base);
  await page.getByRole('heading', { name: 'CareGuide', exact: true }).waitFor();
  await stamp('LOCAL Amplify bundle verification — not a cloud deployment');
  await page.screenshot({ path: output + '/local-desktop.png', fullPage: true });
  await page.goto(base + '/new');
  await page.reload();
  await page.locator('#facilityName').waitFor();
  results.push('Direct navigation and refresh on SPA /new route');
  await page.locator('#appointmentType').selectOption('MRI');
  await page.locator('#appointmentDate').fill('2026-10-20');
  await page.locator('#facilityName').fill('Example Family Clinic');
  await page.locator('#reasonForVisit').fill('Prepare questions for my scheduled appointment.');
  await page.locator('#officialInstructions').fill('Arrive 30 minutes early. Bring photo identification.');
  await page.locator('form button').click();
  await page.getByRole('heading', { name: 'Your CareGuide', exact: true }).waitFor();
  results.push('Browser guide generation through same-origin API');
  const guideUrl = page.url();
  await page.getByRole('checkbox').first().check();
  await page.reload();
  assert(await page.getByRole('checkbox').first().isChecked(), 'Checklist persists after reload');
  await stamp('LOCAL generated guide — fictional appointment');
  await page.screenshot({ path: output + '/local-guide.png', fullPage: true });
  await page.goto(base + '/guides');
  await page.locator('tr').filter({ hasText: 'Example Family Clinic' }).getByRole('link', { name: 'View', exact: true }).click();
  assert(page.url() === guideUrl, 'Saved guide can be reopened');
  await page.goto(base + '/guides');
  page.on('dialog', dialog => dialog.accept());
  await page.locator('tr').filter({ hasText: 'Example Family Clinic' }).getByRole('button', { name: 'Delete', exact: true }).click();
  assert(await page.locator('tr').filter({ hasText: 'Example Family Clinic' }).count() === 0, 'Saved guide deletion');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile home has no horizontal overflow');
  await stamp('LOCAL mobile viewport verification');
  await page.screenshot({ path: output + '/local-mobile.png', fullPage: true });
  await page.goto(base + '/new');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile form has no horizontal overflow');
  assert(errors.length === 0, 'No browser JavaScript errors');
  await page.setViewportSize({ width: 1280, height: 1000 });
  await page.goto('https://github.com/naigambhatt98/careguide-workshop5', { waitUntil: 'domcontentloaded' });
  await page.locator('a[href$="/amplify.yml"]:visible').first().waitFor();
  await stamp('GitHub repository evidence');
  await page.screenshot({ path: output + '/github-repository.png' });
  fs.writeFileSync(output + '/verification.json', JSON.stringify({ capturedAt: new Date().toISOString(), baseUrl: base, cloudVerified: false, results, errors }, null, 2));
  console.log(JSON.stringify({ results, errors }, null, 2));
  await browser.close();
})().catch(err => { console.error(err); process.exitCode = 1; });
